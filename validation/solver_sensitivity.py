"""Solver sensitivity of the IndPenSim-faithful simulation.

Runs the same batches with several ODE solver settings and reports how far key variables move relative to
a tight-tolerance reference. This spread is the floor for any comparison with other implementations
(e.g. MATLAB ``ode15s``): differences below it cannot be told apart from solver error.

    python validation/solver_sensitivity.py --seeds 1 2 3 --out docs/solver_sensitivity.md
"""

from __future__ import annotations

import argparse
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

from penicillium import RamanMode, SimulationConfig, Simulator

VARIABLES = ["P", "X", "S", "V", "DO2", "T", "pH", "PAA", "NH3", "CO2outgas"]

SETTINGS: dict[str, dict] = {
    "reference": {"solver": "lsoda", "rtol": 1e-9, "atol": 1e-12},
    "lsoda (default)": {"solver": "lsoda"},
    "bdf": {"solver": "bdf"},
    "lsoda rtol=1e-7": {"solver": "lsoda", "rtol": 1e-7, "atol": 1e-9},
}


def run(seed: int, name: str):
    t0 = time.perf_counter()
    config = SimulationConfig(raman_mode=RamanMode.PAT_CONTROL, raman_noise=False)
    res = Simulator(config=config, **SETTINGS[name]).run(seed=seed)
    return seed, name, {v: res[v] for v in VARIABLES}, res.total_yield, time.perf_counter() - t0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seeds", type=int, nargs="+", default=[1, 2, 3])
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()

    with ProcessPoolExecutor(args.jobs) as pool:
        futures = [pool.submit(run, s, n) for s in args.seeds for n in SETTINGS]
        results = {(s, n): (data, y, rt) for s, n, data, y, rt in (f.result() for f in futures)}

    lines = [
        "# Solver sensitivity",
        "",
        "Generated by `validation/solver_sensitivity.py`. Each setting is compared with a tight-tolerance LSODA",
        "run (`rtol=1e-9`, `atol=1e-12`) of the same batch. Values are the maximum over the batch of",
        "`|x - x_ref| / max(|x_ref|)` per variable (so relative to the variable's range), then the maximum over",
        f"seeds {args.seeds}. Final yield difference is relative. Runtime is the mean per batch. The batches",
        "run under PAT control of PAA with noise-free spectra, so the yields differ from the default recipe.",
        "",
        "| setting | runtime [s] | yield diff | " + " | ".join(VARIABLES) + " |",
        "|---|---|---|" + "---|" * len(VARIABLES),
    ]
    for name in SETTINGS:
        errs = {v: 0.0 for v in VARIABLES}
        ydiff = 0.0
        runtimes = []
        for s in args.seeds:
            ref, yref, _ = results[(s, "reference")]
            data, y, rt = results[(s, name)]
            runtimes.append(rt)
            ydiff = max(ydiff, abs(y - yref) / abs(yref))
            for v in VARIABLES:
                errs[v] = max(errs[v], float(np.max(np.abs(data[v] - ref[v])) / np.max(np.abs(ref[v]))))
        cells = " | ".join(f"{errs[v]:.1e}" for v in VARIABLES)
        lines.append(f"| {name} | {np.mean(runtimes):.0f} | {ydiff:.1e} | {cells} |")
    lines.append("")
    lines.append("Final yields [kg]: " + ", ".join(
        f"seed {s}: {results[(s, 'reference')][1]:.1f}" for s in args.seeds
    ))  # fmt: skip
    text = "\n".join(lines) + "\n"
    print(text)
    if args.out:
        args.out.write_text(text)


if __name__ == "__main__":
    main()
