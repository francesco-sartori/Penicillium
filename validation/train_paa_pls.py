"""Train the PLS model behind the ``PAA_pred`` channel (needs scikit-learn).

IndPenSim (``Substrate_prediction.m``) predicts PAA from each Raman spectrum with a 4-latent-variable PLS model on
the Savitzky-Golay-smoothed (order 2, window 5) first derivative of the spectrum, restricted to points 350-500 and
800-860 (MATLAB indices). Its coefficients (``PAA_PLS_model.mat``) were fitted by the IndPenSim authors and are not
redistributed here. This script fits a model of the same form on spectra simulated by Penicillium and writes
``src/penicillium/_paa_pls.py``:

    python validation/train_paa_pls.py

Training batches use seeds disjoint from the scenario and test seeds (900_000 + i), PRBS feeds and PAT control, so
PAA moves over the range the controller produces.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from sklearn.cross_decomposition import PLSRegression

from penicillium import BatchSpec, RamanMode, SimulationConfig, simulate_batches
from penicillium.raman import paa_pls_features

OUT = Path(__file__).parents[1] / "src" / "penicillium" / "_paa_pls.py"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n-batches", type=int, default=12)
    ap.add_argument("--jobs", type=int, default=None)
    args = ap.parse_args()
    configs = [
        SimulationConfig(raman_mode=RamanMode.PAT_CONTROL, prbs=True),
        SimulationConfig(raman_mode=RamanMode.RECORD, prbs=True),
    ]
    specs = [BatchSpec(seed=900_000 + i, config=configs[i % 2]) for i in range(args.n_batches)]
    results = simulate_batches(specs, n_jobs=args.jobs)
    X = np.vstack([paa_pls_features(r.raman[10:]) for r in results])
    y = np.concatenate([r["PAA"][10:] for r in results])
    pls = PLSRegression(n_components=4, scale=False).fit(X, y)
    coef = np.asarray(pls.coef_, dtype=float).reshape(-1)
    # predict() centres X before applying coef_, so the raw-space intercept is the prediction at X = 0.
    intercept = float(np.ravel(pls.predict(np.zeros((1, X.shape[1]))))[0])
    pred = X @ coef + intercept
    assert np.allclose(pred, np.ravel(pls.predict(X)))
    rmse = float(np.sqrt(np.mean((pred - y) ** 2)))
    print(
        f"{len(y)} spectra from {len(results)} batches, training RMSE {rmse:.1f} mg/L (PAA {y.min():.0f}-{y.max():.0f})"
    )
    lines = [
        '"""PLS coefficients of the ``PAA_pred`` channel. Generated by ``validation/train_paa_pls.py``; do not edit.',
        "",
        f"Fitted on {len(y)} spectra of {len(results)} Penicillium batches "
        f"(seeds 900000-{900_000 + args.n_batches - 1}),",
        f'4 latent variables, training RMSE {rmse:.1f} mg/L."""',
        "",
        f"INTERCEPT = {intercept!r}",
        "COEF = [",
        *(f"    {float(c)!r}," for c in coef),
        "]",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
